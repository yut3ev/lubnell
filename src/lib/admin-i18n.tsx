// ── core translation ──
export function translate(lang: AdminLang, source: string): string {
  if (lang === "ar") return source;
  return ADMIN_EN[source] ?? source;
}
export function runtimeT(source: string): string { return translate(runtimeLang, source); }

// Read the persisted studio language (usePersistedState JSON-encodes values).
export function readStoredAdminLang(): AdminLang {
  try {
    const raw = typeof window === "undefined" ? null : window.localStorage.getItem("lubnel-admin-lang");
    const parsed = raw ? JSON.parse(raw) : null;
    return parsed === "en" ? "en" : "ar";
  } catch { return "ar"; }
}
// Runtime (non-React) currency formatter for socket-event toasts.
export function runtimeMoney(value: number): string {
  return `${(value ?? 0).toLocaleString("en-US")} ${runtimeLang === "ar" ? "ج.م" : "EGP"}`;
}

// ── React context for render-time strings ──
type AdminLangValue = { lang: AdminLang; setLang: (l: AdminLang) => void; ar: boolean; t: (s: string) => string };
const AdminLangCtx = createContext<AdminLangValue>({ lang: "ar", setLang: () => undefined, ar: true, t: s => s });

export function AdminLangProvider({ lang, setLang, children }: { lang: AdminLang; setLang: (l: AdminLang) => void; children: ReactNode }) {
  const value = useMemo<AdminLangValue>(() => ({
    lang,
    setLang,
    ar: lang === "ar",
    t: (s: string) => translate(lang, s),
  }), [lang, setLang]);
  return <AdminLangCtx.Provider value={value}>{children}</AdminLangCtx.Provider>;
}

export function useAdminLangCtx() { return useContext(AdminLangCtx); }
export function useAdminT() {
  const { t } = useContext(AdminLangCtx);
  return t;
}
export function useAdminAr() {
  const { ar } = useContext(AdminLangCtx);
  return ar;
}
export function useAdminDateLocale() {
  const { ar } = useContext(AdminLangCtx);
  return ar ? "ar-EG" : "en-GB";
}
// Locale-aware currency formatter for admin surfaces (ج.م in AR, EGP in EN).
export function useAdminMoney() {
  const { ar } = useContext(AdminLangCtx);
  return useCallback((value: number) => `${(value ?? 0).toLocaleString("en-US")} ${ar ? "ج.م" : "EGP"}`, [ar]);
}
